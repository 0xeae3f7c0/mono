#!/usr/bin/env node
// repository tooling (scripts/)
// Writes the Backstage catalog for the portal (pkgs/portal/examples/entities.yaml):
// one Component per project in pkgs/ plus the root CLI, grouped into the
// `commit` System. Descriptions come from each project's manifest.
// `--check` fails if the file is out of date (CI runs this).
//
//   node scripts/gen-catalog.mjs [--check]

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const check = process.argv.includes("--check");
const out = "pkgs/portal/examples/entities.yaml";

// Role of each project in the platform: [type, lifecycle-stage group].
const roles = {
  website: "website", docs: "documentation", changelog: "website", "status-page": "website",
  dashboard: "website", admin: "website", widget: "library", reports: "website", portal: "website",
  mobile: "mobile-app", desktop: "desktop-app", inspector: "desktop-app", "runner-monitor": "tool",
};

function describe(dir) {
  const pkg = join(dir, "package.json");
  if (existsSync(pkg)) return JSON.parse(readFileSync(pkg, "utf8")).description ?? "";
  const cargo = join(dir, "src", "main.rs");
  if (existsSync(cargo)) return firstDocLine(readFileSync(cargo, "utf8"), /^\/\/! ?(.*)$/);
  const go = join(dir, "main.go");
  if (existsSync(go)) return firstDocLine(readFileSync(go, "utf8"), /^\/\/ ?(.*)$/);
  return "";
}

function firstDocLine(text, re) {
  const lines = [];
  // Skip the one-line "<project>: ... (commit platform, pkgs/<project>)" file header.
  for (const line of text.split("\n").filter((l) => !l.includes("(commit platform, pkgs/"))) {
    const m = line.match(re);
    if (!m) break;
    if (!m[1].trim()) break;
    lines.push(m[1].trim());
  }
  return lines.join(" ").replace(/^Command \S+ /, "");
}

function type(name, dir) {
  if (roles[name]) return roles[name];
  if (existsSync(join(dir, "go.mod")) || existsSync(join(dir, "Cargo.toml"))) {
    return /\b(serve|listen|HTTP|API|gRPC|Worker|worker)\b/.test(describe(dir)) ? "service" : "tool";
  }
  return "service";
}

const quote = (s) => JSON.stringify(s);
const components = readdirSync("pkgs", { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const dir = `pkgs/${name}`;
    return [
      "---",
      "apiVersion: backstage.io/v1alpha1",
      "kind: Component",
      "metadata:",
      `  name: ${name}`,
      `  description: ${quote(describe(dir) || name)}`,
      "  annotations:",
      `    github.com/project-slug: 0xeae3f7c0/mono`,
      `    backstage.io/source-location: url:https://github.com/0xeae3f7c0/mono/tree/main/${dir}`,
      "spec:",
      `  type: ${type(name, dir)}`,
      "  lifecycle: production",
      "  owner: platform",
      "  system: commit",
    ].join("\n");
  });

const text = [
  "# Generated by scripts/gen-catalog.mjs from the projects in pkgs/. Do not edit by hand.",
  "apiVersion: backstage.io/v1alpha1",
  "kind: System",
  "metadata:",
  "  name: commit",
  "  description: Self-hosted engineering-activity platform",
  "spec:",
  "  owner: platform",
  "---",
  "apiVersion: backstage.io/v1alpha1",
  "kind: Component",
  "metadata:",
  "  name: cli",
  "  description: Repository validation CLI (crates/)",
  "spec:",
  "  type: tool",
  "  lifecycle: production",
  "  owner: platform",
  "  system: commit",
  ...components,
  "",
].join("\n");

const current = existsSync(out) ? readFileSync(out, "utf8") : null;
if (current === text) {
  console.log(`${out} is up to date.`);
} else if (check) {
  console.error(`out of date: ${out} (run node scripts/gen-catalog.mjs)`);
  process.exit(1);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${components.length + 1} components)`);
}
